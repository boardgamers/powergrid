'use strict';
// Worker boundary carries only bounded public observations and bound indices.
// No game state, seeds, move construction, network, child processes or model logs.
const { isMainThread, parentPort, workerData } = require('node:worker_threads');
const { hash, canonical, requireThat } = require('./identity.cjs');
const { OnnxPolicy, validateRequest, validateResponse, MAX_REQUEST, remember } = require('./onnx.cjs');

class RequestSession {
    #policy;
    #cache = new Map();
    constructor(policy) {
        this.#policy = policy;
    }
    async handle(request) {
        validateRequest(request, this.#policy.replica);
        const raw = canonical(request);
        requireThat(Buffer.byteLength(raw) <= MAX_REQUEST, 'worker-request-limit');
        const payload = hash(raw);
        const previous = this.#cache.get(request.requestId);
        if (previous) {
            requireThat(previous.payload === payload, 'worker-request-conflict');
            remember(this.#cache, request.requestId, previous);
            return { ...previous.response };
        }
        const result = await this.#policy.evaluate(request.observation);
        const response = {
            schema: 'pg-replica-serving-response-v1',
            requestId: request.requestId,
            replica: this.#policy.replica,
            checkpointSha256: this.#policy.checkpointSha256,
            index: result.index,
            actionCount: request.observation.actions.length,
        };
        validateResponse(response, request);
        remember(this.#cache, request.requestId, { payload, response: Object.freeze(response) });
        return { ...response }; // Never send logits or the uncalibrated value head to the host.
    }
}

async function serve() {
    let policy;
    let session;
    let stopped = false;
    let pending = 0;
    let chain = Promise.resolve();
    function fail(code) {
        if (stopped) return;
        stopped = true;
        try {
            parentPort.postMessage({ schema: 'pg-replica-serving-error-v1', code });
        } catch (_) {
            /* port closed */
        }
        parentPort.close();
        process.exitCode = 1;
        policy?.close().catch(() => {});
    }
    parentPort.on('messageerror', () => fail('invalid-request'));
    parentPort.on('message', (raw) => {
        if (stopped) return;
        try {
            requireThat(
                session &&
                    typeof raw === 'string' &&
                    raw.length <= MAX_REQUEST &&
                    Buffer.byteLength(raw) <= MAX_REQUEST &&
                    pending < 8,
                'worker-request-limit'
            );
            const request = JSON.parse(raw);
            // Only canonical JSON generated by the transport: no duplicate keys,
            // NaN, ambiguous numeric spellings or surplus fields accepted.
            validateRequest(request, policy.replica);
            requireThat(canonical(request) === raw, 'worker-json');
            pending++;
            chain = chain
                .then(async () => {
                    if (stopped) return;
                    const response = await session.handle(request);
                    if (!stopped) parentPort.postMessage(response);
                })
                .catch(() => fail('invalid-request'))
                .finally(() => {
                    pending--;
                });
        } catch (_) {
            fail('invalid-request');
        }
    });
    parentPort.on('close', () => {
        stopped = true;
        policy?.close().catch(() => {});
    });
    try {
        policy = await OnnxPolicy.create(workerData);
        requireThat(policy.manifestSha256 === workerData.sourceManifestSha256, 'worker-source-identity');
        if (stopped) {
            await policy.close();
            return;
        }
        session = new RequestSession(policy);
        parentPort.postMessage({
            schema: 'pg-replica-serving-ready-v1',
            replica: policy.replica,
            checkpointSha256: policy.checkpointSha256,
            manifestSha256: policy.manifestSha256,
        });
    } catch (_) {
        fail('startup-failed');
    }
}

if (!isMainThread && require.main === module) {
    // Native inference is sequential. worker_threads are lifecycle isolation,
    // not a security sandbox or a hard native-execution interruption guarantee.
    serve().catch(() => {
        parentPort.close();
        process.exitCode = 1;
    });
}
module.exports = { RequestSession };
