"""Preserve successful snapshot-route replays and the original failed adapter."""
from datetime import datetime,timezone
import json
from pathlib import Path
import shutil

from huggingface_hub import HfApi
from policy_iteration_evidence_archive import upload_evidence
from public_policy_development_job_v1 import digest,read

ROOT=Path(__file__).resolve().parents[2]
NAME='resource-turn-snapshot-adapter-evidence-v1'
OUT=ROOT/'ai/runs'/NAME
RESULT=ROOT/'ai/strong'/(NAME+'.json')


def save(path,value):
    with path.open('x') as stream:json.dump(value,stream,indent=2,allow_nan=False);stream.write('\n')


def main():
    for path in (OUT,OUT.with_suffix('.tgz'),OUT.with_suffix('.intent.json'),RESULT):
        assert not path.exists(),'Inspect prior archive intent/outcome before retry'
    run=ROOT/'ai/runs/resource-turn-snapshot-adapter-v2';failed=ROOT/'ai/runs/resource-turn-snapshot-adapter-v1'
    report=ROOT/'ai/strong/resource-turn-snapshot-adapter-results-v1.json'
    assessment=read(run/'assessment.json');plan=read(run/'plan.json')
    assert assessment['passed'] and digest(run/'assessment.json')==read(report)['assessment_sha256']
    assert assessment['recorded_game_replays']==24 and assessment['distinct_original_games']==12
    assert assessment['tampered_inputs_rejected']==6 and assessment['new_full_game_trajectories']==0
    assert all(digest(ROOT/name)==sha for key in ('code_hashes','input_hashes') for name,sha in assessment[key].items())
    assert all(digest(run/name)==sha for name,sha in assessment['output_hashes'].items())
    assert digest(run/'plan.json')==assessment['plan_sha256']
    assert read(failed/'failure-summary.json')['completed_replays']==0
    assert digest(failed/'failure-summary.json')==plan['preserved_failed_attempt']['summary_sha256']
    assert digest(failed/'plan.json')==plan['preserved_failed_attempt']['plan_sha256']
    assert all(digest(failed/'original-source'/name)==sha for name,sha in read(failed/'plan.json')['code_hashes'].items())
    sources={Path(__file__).resolve(),report,run.with_suffix('.log'),failed.with_suffix('.log')}
    for directory in (run,failed):sources.update(p for p in directory.rglob('*') if p.is_file())
    sources.update(ROOT/name for name in assessment['code_hashes'])
    sources.update(ROOT/'ai/strong'/name for name in (
        'resource-turn-runtime-source-v1.json','resource-turn-runtime-launch-evidence-v1.json',
        'resource-turn-anchored-policy-evidence-v1.json','resource-replanning-development-complete-evidence-v1.json',
        'conservative-auction-development-source-v2.json','final-protocol-multiplayer.json',
        'policy_iteration_evidence_archive.py','strategic_collection.py'))
    sources.update(ROOT/'ai/runs/resource-turn-full-artifact-v3'/name for name in ('manifest.json','resource-full-descriptor.json'))
    sources.update(ROOT/'ai'/name for name in ('RESOURCE-TURN-SNAPSHOT-2026-10-28.md',
        'RESOURCE-TURN-RUNTIME-2026-10-28.md','RESUME.md'))
    pilot=ROOT/'ai/runs/resource-turn-runtime-hf-v1/pg-resource-turn-runtime-v1-whole-2p'
    sources.update(pilot/name for name in ('verified.json','independent-audit/result.json'))
    api=HfApi();repo='coyotte508/powergrid-ai-germany-v1'
    assert api.model_info(repo).private
    assert not api.file_exists(repo,'archives/'+NAME+'.tgz'),'Inspect existing remote archive'
    OUT.mkdir();hashes={}
    for source in sorted(sources):
        assert source.is_file() and not source.is_symlink()
        name=str(source.relative_to(ROOT));target=OUT/name;target.parent.mkdir(parents=True,exist_ok=True)
        before=digest(source);shutil.copy2(source,target);assert digest(target)==before;hashes[name]=before
    note=OUT/'README.md'
    note.write_text('''# Resource-policy neural snapshot opponent route

Twelve historical A260 games, all seats and rules, reproduced through both the
atomic and complete-resource-turn controls. Independent engine/model replay and
six negative checks are included. The initial failed adapter, its sources and
partial receipts are preserved. No original engine, model or running study was
changed. No new independent games, search rollouts, gradients or HF jobs were
generated by this adapter validation. It does not select or qualify a policy.

The unchanged v3 artifact source, A260 weights and historical input games are
recoverable from the included immutable source/evidence descriptors. The small
verified receipt for the first resource runtime pilot references its separate
immutable raw job archive; it is runtime evidence, not strength evidence.
''');hashes[note.name]=digest(note);save(OUT/'manifest.json',hashes)
    intent={'created_at':datetime.now(timezone.utc).isoformat(),'stage':'prepared_for_upload',
        'archive_path':'archives/'+NAME+'.tgz','manifest_sha256':digest(OUT/'manifest.json')}
    save(OUT.with_suffix('.intent.json'),intent)
    print(json.dumps({'stage':'uploading','files':len(hashes)+1}),flush=True)
    archive=upload_evidence(OUT)
    save(RESULT,{'status':'recorded_neural_snapshot_route_verified_not_strength_tested',
        'assessment_sha256':digest(run/'assessment.json'),'plan_sha256':digest(run/'plan.json'),
        'recorded_game_replays':24,'distinct_original_games':12,'modes':assessment['modes'],
        'tampered_inputs_rejected':6,'preserved_failed_attempt':plan['preserved_failed_attempt'],
        'new_hf_jobs':0,'new_full_game_trajectories':0,'new_strength_games':0,'new_gradients':0,
        'qualification_eligible':False,'reserved_final_seeds_used':False,'archive':archive})
    OUT.with_suffix('.intent.json').write_text(json.dumps({**intent,'stage':'uploaded_download_verified',
        'archive':archive,'descriptor_sha256':digest(RESULT)},indent=2)+'\n')
    print(json.dumps(archive),flush=True)


if __name__=='__main__':main()
