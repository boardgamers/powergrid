// Writes engine/src/maps/chile-board.ts from the Chile design's board data (chile-map-data.json, the source of truth).
//   node scripts/generate-chile-map.mjs <path to chile-map-data.json>
// Regions become their colours (as on the other maps); Salta, in no region, gets the empty region ''. Each city
// carries its grid (North or Central).
// Connections marked closedUntilStep3 go to step3Connections, which join the board when Step 3 begins.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const source = process.argv[2];
if (!source) {
    console.error('usage: node scripts/generate-chile-map.mjs <chile-map-data.json>');
    process.exit(1);
}
const data = JSON.parse(fs.readFileSync(source, 'utf8'));
const colour = Object.fromEntries(data.regions.map((r) => [r.name, r.color]));
const q = (s) => `'${s.replace(/'/g, "\\'")}'`;

const cities = data.cities.map((c) => {
    const extra = c.singleOccupancy ? ', singleOccupancy: true' : '';
    if (c.grid !== 'North' && c.grid !== 'Central') throw new Error(`${c.name} has no grid`);
    const region = q(c.region ? colour[c.region] : '');
    return `    { name: ${q(c.name)}, region: ${region}, grid: ${q(c.grid)}, x: ${c.x}, y: ${c.y}${extra} },`;
});
const conn = (c) => `    { nodes: [${q(c.nodes[0])}, ${q(c.nodes[1])}], cost: ${c.cost} },`;
const open = data.connections.filter((c) => !c.closedUntilStep3).map(conn);
const gates = data.connections.filter((c) => c.closedUntilStep3).map(conn);

const out = `// Generated by scripts/generate-chile-map.mjs from the Chile design's chile-map-data.json. Do not edit by hand:
// change the design and regenerate.
import { City, Connection } from './../maps';

export const chileRegions = ${JSON.stringify(Object.fromEntries(data.regions.map((r) => [r.color, r.name])))};

export const chileViewBox: [number, number] = [${data.viewBox[0]}, ${data.viewBox[1]}];

export const chileCities: City[] = [
${cities.join('\n')}
];

export const chileConnections: Connection[] = [
${open.join('\n')}
];

/** The gates between the grids: closed until Step 3. */
export const chileGates: Connection[] = [
${gates.join('\n')}
];
`;
const target = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'engine', 'src', 'maps', 'chile-board.ts');
fs.writeFileSync(target, out);
console.log(`wrote ${target}: ${data.cities.length} cities, ${open.length} connections, ${gates.length} gates`);
